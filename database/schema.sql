-- Name: v_current_debtors; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.v_current_debtors AS
 SELECT d.id_debt,
    d.id_contract,
    c.contract_number,
    (((((s.last_name)::text || ' '::text) || (s.first_name)::text) || ' '::text) || (COALESCE(s.middle_name, ''::character varying))::text) AS student_fio,
    d.occurrence_date,
    d.debt_amount,
    d.paid_amount,
    (d.debt_amount - d.paid_amount) AS outstanding,
    (CURRENT_DATE - d.occurrence_date) AS days_overdue,
        CASE
            WHEN ((CURRENT_DATE - d.occurrence_date) <= 7) THEN 'green'::text
            WHEN ((CURRENT_DATE - d.occurrence_date) <= 14) THEN 'yellow'::text
            ELSE 'red'::text
        END AS color_indicator
   FROM ((public.debt d
     JOIN public.contract c ON ((c.id_contract = d.id_contract)))
     JOIN public.student s ON ((s.id_student = c.id_student)))
  WHERE ((d.status)::text = ANY (ARRAY[('активна'::character varying)::text, ('частично_погашена'::character varying)::text]));


